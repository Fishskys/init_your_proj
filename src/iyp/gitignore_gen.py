LABELS["logs"] = "日志文件"


def _menu(title: str, items: list[tuple[str, str]]) -> list[str]:
    print(c(title, BOLD))
    for i, (key, label) in enumerate(items, 1):
        print(f"  {i:>2}. {label}")
    print(c("输入序号，逗号或空格分隔（默认: 不选任何语言）:", CYAN))
    raw = input("> ").replace(",", " ").split()
    picked = []
    for tok in raw:
        if tok.isdigit() and 1 <= int(tok) <= len(items):
            picked.append(items[int(tok) - 1][0])
    return picked


def _yes_no(prompt: str, default: bool = False) -> bool:
    d = "y" if default else "n"
    ans = input(c(f"{prompt} [y/n]（默认: {d}）: ", CYAN)).strip().lower()
    if not ans:
        return default
    return ans in ("y", "yes")


def build_gitignore() -> str:
    langs = _menu("项目使用哪些语言/运行时？", LANG_LABELS)
    ai_dirs = _yes_no("是否把 AI agent 工具目录加入 .gitignore？")
    keys = langs + DEFAULT_KEYS + (["hermes_ai"] if ai_dirs else [])
    blocks: dict[str, list[str]] = {}
    for key in keys:
        blocks[key] = SEGMENTS[key]
    lines: list[str] = [MARK]
    for key, seg in blocks.items():
        lines += ["", f"# --- {LABELS.get(key, key)} ---", *seg]
    return "\n".join(lines).rstrip() + "\n"


def _parse_segments(addition: str) -> list[tuple[str, list[str]]]:
    """把 build_gitignore 的产物拆成分组列表 [(分组标签, 该组行), ...]。"""
    segs: list[tuple[str, list[str]]] = []
    cur_label: str | None = None
    cur_lines: list[str] = []
    for line in addition.splitlines():
        s = line.strip()
        if s.startswith("# --- ") and s.endswith(" ---"):
            if cur_label is not None:
                segs.append((cur_label, cur_lines))
            cur_label = s[len("# --- "):-len(" ---")]
            cur_lines = []
        elif s.startswith("# ----"):      # 工具标记行，不作为分组
            continue
        elif cur_label is not None and s:
            cur_lines.append(line)
    if cur_label is not None:
        segs.append((cur_label, cur_lines))
    return segs


def merge(existing: str, addition: str) -> tuple[str, int]:
    """按分组追加：同名 `# --- 分组 ---` 段内补行，缺段则整段带注释追加。

    与旧实现（逐行裸追加、丢掉注释与空行）的区别：保留分组注释与空行结构，
    使用户在已有 .gitignore 上追加时仍按语言/用途分段可读。
    两阶段处理：① 先在原文件内补全同名分组（按行号倒序插入，避免偏移）；
    ② 再把全新的分组带注释追加到末尾。
    返回 (新内容, 新增行数)。
    """
    segs = _parse_segments(addition)
    lines = existing.rstrip("\n").splitlines() if existing.strip() else []
    have = {l.strip() for l in lines if l.strip() and not l.strip().startswith("#")}
    added = 0

    # ---- 阶段 1：定位原文件已有的分组头 ----
    headers: dict[str, int] = {}
    for i, l in enumerate(lines):
        s = l.strip()
        if s.startswith("# --- ") and s.endswith(" ---"):
            headers.setdefault(s[len("# --- "):-len(" ---")], i)

    same_group: list[tuple[int, list[str]]] = []   # (header 行号, 缺失行)
    new_groups: list[tuple[str, list[str]]] = []
    for label, seg_lines in segs:
        missing = [l for l in seg_lines if l.strip() and l.strip() not in have]
        if not missing:
            continue
        for l in missing:
            have.add(l.strip())
        if label in headers:
            same_group.append((headers[label], missing))
        else:
            new_groups.append((label, missing))

    # ---- 阶段 1 执行：从后往前插入，行号不受影响 ----
    HEAD = lambda s: s.strip().startswith("# --- ") and s.strip().endswith(" ---")
    for idx, missing in sorted(same_group, key=lambda x: -x[0]):
        end = len(lines)
        for j in range(idx + 1, len(lines)):
            if HEAD(lines[j]):
                end = j
                break
        insert_at = end
        while insert_at - 1 > idx and not lines[insert_at - 1].strip():
            insert_at -= 1
        for off, l in enumerate(missing):
            lines.insert(insert_at + off, l)
        added += len(missing)

    # ---- 阶段 2：追加全新分组（整段带注释）----
    for label, missing in new_groups:
        if lines and lines[-1].strip():
            lines.append("")
        if MARK not in {l.strip() for l in lines}:
            lines.append(MARK)
            lines.append("")
        lines.append(f"# --- {label} ---")
        lines.extend(missing)
        added += len(missing)

    if added == 0:
        return (existing if existing.endswith("\n") else existing + "\n"), 0
    return "\n".join(lines).rstrip() + "\n", added


def cmd_ignore_flow(root: Path) -> int:
    """在给定项目根下交互式生成 .gitignore（供 init 调用）。"""
    print(c("— 现在开始生成 .gitignore 文件 —", BOLD))
    target = root / ".gitignore"
    addition = build_gitignore()
    if target.exists():
        old = target.read_text(encoding="utf-8")
        new, n = merge(old, addition)
        if n == 0:
            print(c(".gitignore 已覆盖全部建议条目，无需修改。", GREEN))
            return 0
        ans = input(c(f"将追加 {n} 行到已有 {target}，继续？[y/n]（默认: y）: ", CYAN)).strip().lower()
        if ans == "n":
            print("已取消。")
            return 0
        target.write_text(new, encoding="utf-8")
        print(c(f"已追加 {n} 行 -> {target}", GREEN))
    else:
        target.write_text(addition, encoding="utf-8")
        print(c(f"已生成 {target}", GREEN))
    return 0
