"""gitignore_gen.py：段落构建与按分组合并（同名补行 / 新组带注释追加 / 幂等）。"""
from __future__ import annotations

import unittest

from init_your_proj.gitignore_gen import (
    DEFAULT_KEYS, LABELS, MARK, SEGMENTS, _parse_segments, build_gitignore, merge,
)


def build(keys):
    """按给定 key 顺序构造 addition（与 build_gitignore 结构一致，跳过交互）。"""
    lines = [MARK]
    for key in keys:
        lines += ["", f"# --- {LABELS.get(key, key)} ---", *SEGMENTS[key]]
    return "\n".join(lines).rstrip() + "\n"


class TestSegments(unittest.TestCase):
    def test_no_stale_init_your_proj_segment(self):
        # 早期「clone 到用户项目」用法的过时段已删除
        self.assertNotIn("init_your_proj", SEGMENTS)
        self.assertNotIn("init_your_proj", LABELS)

    def test_default_keys_are_four(self):
        self.assertEqual(DEFAULT_KEYS, ["editor", "env", "tmp", "logs"])

    def test_all_segments_non_empty(self):
        for k, v in SEGMENTS.items():
            self.assertTrue(v, f"段 {k} 为空")

    def test_language_segments_present(self):
        for k in ("python", "node", "rust", "go", "java", "c_cpp",
                  "dotnet", "html_css", "lua", "ruby"):
            self.assertIn(k, SEGMENTS)


class TestParseSegments(unittest.TestCase):
    def test_parse_structure(self):
        addition = build(["python", "editor"])
        segs = _parse_segments(addition)
        labels = [s[0] for s in segs]
        self.assertEqual(labels, [LABELS["python"], LABELS["editor"]])
        # 每段行数与 SEGMENTS 一致
        self.assertEqual(segs[0][1], SEGMENTS["python"])

    def test_marker_line_not_a_segment(self):
        segs = _parse_segments(build(["python"]))
        for label, _ in segs:
            self.assertNotIn("generated by", label)


class TestMerge(unittest.TestCase):
    def test_empty_existing_appends_grouped(self):
        new, n = merge("", build(["python"]))
        self.assertGreater(n, 0)
        self.assertIn(MARK, new)
        self.assertIn("# --- Python ---", new)
        for line in SEGMENTS["python"]:
            self.assertIn(line, new)

    def test_existing_without_groups_gets_comments(self):
        existing = "# my project\nnode_modules/\n*.log\n"
        new, n = merge(existing, build(["python", "editor", "env", "tmp", "logs"]))
        # 原有内容保留
        self.assertTrue(new.startswith("# my project\nnode_modules/\n*.log\n"))
        # 新增部分带分组注释
        for key in ("python", "editor", "env", "tmp", "logs"):
            self.assertIn(f"# --- {LABELS[key]} ---", new)
        self.assertGreater(n, 0)

    def test_same_group_fills_in_place(self):
        existing = ("# my project\n\n# --- Python ---\n__pycache__/\n\n"
                    "# --- 日志文件 ---\n*.log\n")
        new, n = merge(existing, build(["python", "logs"]))
        lines = new.splitlines()
        # 缺失的 python 行应插在原 Python 组内（在“日志文件”组头之前）
        log_idx = lines.index("# --- 日志文件 ---")
        py_idx = lines.index("# --- Python ---")
        py_block = lines[py_idx:log_idx]
        self.assertIn("*.py[cod]", py_block)          # 补进 Python 组
        self.assertIn("*.pytest_cache/".replace("*.", "."), py_block) \
            if ".pytest_cache/" in SEGMENTS["python"] else None
        # 日志组补入 logs/
        self.assertIn("logs/", lines[log_idx:])

    def test_new_groups_appended_after_same_group_fill(self):
        existing = "# --- Python ---\n__pycache__/\n"
        new, n = merge(existing, build(["python", "editor"]))
        lines = new.splitlines()
        py_idx = lines.index("# --- Python ---")
        ed_idx = lines.index("# --- 编辑器/系统垃圾文件 ---")
        self.assertLess(py_idx, ed_idx)               # 同名组在前，新组在后
        self.assertIn(".pytest_cache/", lines[py_idx:ed_idx])

    def test_idempotent(self):
        new1, n1 = merge("# base\n", build(["python", "editor", "env", "tmp", "logs"]))
        new2, n2 = merge(new1, build(["python", "editor", "env", "tmp", "logs"]))
        self.assertEqual(n2, 0)
        self.assertEqual(new1, new2)

    def test_no_trailing_newline_input(self):
        new, n = merge("node_modules/", build(["python"]))
        self.assertTrue(new.startswith("node_modules/\n"))
        self.assertGreater(n, 0)

    def test_all_present_returns_zero(self):
        new1, _ = merge("", build(["editor"]))
        new2, n2 = merge(new1, build(["editor"]))
        self.assertEqual(n2, 0)
        self.assertEqual(new1, new2)

    def test_duplicate_lines_not_added(self):
        existing = "# --- Python ---\n__pycache__/\n*.py[cod]\n"
        new, n = merge(existing, build(["python"]))
        self.assertEqual(new.count("__pycache__/"), 1)
        self.assertEqual(new.count("*.py[cod]"), 1)


class TestBuildGitignoreStructure(unittest.TestCase):
    def test_build_output_has_marker_and_groups(self):
        # build_gitignore 会交互，这里验证拼装逻辑的一致性（用 build 辅助对照）
        addition = build(["python", "editor", "env", "tmp", "logs"])
        self.assertTrue(addition.startswith(MARK))
        self.assertEqual(addition.count("# --- "), 5)


if __name__ == "__main__":
    unittest.main()
